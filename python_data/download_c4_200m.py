"""Download C4_200M (synthetic GEC pairs), symlink into `data/`, AND repack a TSV shard to Parquet.

Modality: text (denoise / grammatical-error-correction pairs).  185M `(input, output)` sentence
pairs generated by corrupting the cleaned English C4 crawl: `input` is the corrupted sentence,
`output` the corrected one — the permissive (Apache-licensed corruption code) workhorse for the
surface-robustness / semantic-regularizer objective.

The corpus ships as a single ~14.9 GB `data.zip` (ten ~4.9 GB `C4_200M.tsv-NNNNN-of-00010` TSV
shards inside).  This single file does both halves: it pulls the zip via `snapshot_download`,
symlinks the corpus dir, then streams ONE TSV shard out of the zip (no full unzip to disk) and
writes it as a `(corrupted, corrected)` Parquet — the columns the registry's default flat extractor
reads.  The repack is a light per-shard column projection, so it runs inline (no separate script).

DISK / DEFERRAL: the unzipped TSVs total ~49 GB.  This driver fetches the one zip and repacks a
SINGLE shard (`--shard 0` by default) — a ~18M-pair parquet sample enough to exercise the parse-gate
and supply representation.  Scale up later by repacking more shards (`--shard 1`, ...); the registry
glob `c4_200m-*.parquet` picks up whatever parquet is on disk and the mixture weight controls
representation.  The zip is kept (not deleted) so further shards can be repacked without re-fetching.

VOLUME CONTROL: the source is a SINGLE `data.zip`, so there is no shard cap on the download — this
driver fetches the one archive.  Corpus volume is controlled by the `--shard` / `--max-rows` knobs
that pick which TSV shard (and how many of its pairs) become parquet; there is deliberately no fake
`--fraction` flag on the download step.

Layout: the zip lands under `<DATA_ROOT>/c4_200m/` with a `data/c4_200m` symlink.

    uv run python_data/download_c4_200m.py
    uv run python_data/download_c4_200m.py --shard 1 --overwrite
    UFORM_DATA_ROOT=$UFORM_DATA_ROOT uv run python_data/download_c4_200m.py    # env-var root
"""

from __future__ import annotations

import argparse
import csv
import io
import os
import sys
import zipfile
from pathlib import Path

import pyarrow
import pyarrow.parquet
from acquire_shared import data_root
from huggingface_hub import snapshot_download

#: Default host data root — overridable via `UFORM_DATA_ROOT`; the symlink target `data/c4_200m`
#: points at.
DEFAULT_DATA_ROOT = str(data_root())
#: C4_200M repository on the hub.
SOURCE_REPO = "liweili/c4_200m"
#: Rows per Parquet row group — bounds writer memory on the ~18M-pair shard.
ROW_GROUP_SIZE: int = 200_000


def download_c4_200m(data_root: str) -> str:
    """Pull the C4_200M zip into the host data root and symlink into `data/`.

    Args:
        data_root: Host data root the symlink farm points at (e.g. `$UFORM_DATA_ROOT`).

    Returns:
        The corpus destination directory holding `data.zip` (and the repacked parquet shards).
    """
    destination = os.path.join(data_root, "c4_200m")
    os.makedirs(destination, exist_ok=True)

    print(f"[c4-200m] downloading {SOURCE_REPO} (~14.9 GB zip)", flush=True)
    snapshot_download(
        repo_id=SOURCE_REPO,
        repo_type="dataset",
        local_dir=destination,
        allow_patterns=["data.zip", "README.md"],
    )
    zip_path = os.path.join(destination, "data.zip")
    if os.path.exists(zip_path):
        print(f"[c4-200m] zip at {zip_path} ({os.path.getsize(zip_path) / 1e9:.1f} GB)", flush=True)

    project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    symlink_path = os.path.join(project_root, "data", "c4_200m")
    if os.path.islink(symlink_path) or os.path.exists(symlink_path):
        if os.path.islink(symlink_path) and os.readlink(symlink_path) == destination:
            print(f"[c4-200m] symlink {symlink_path} -> {destination} already correct", flush=True)
            return destination
        os.unlink(symlink_path)
    os.symlink(destination, symlink_path)
    print(f"[c4-200m] symlinked {symlink_path} -> {destination}", flush=True)
    return destination


def repack(zip_path: Path, shard: int, out_dir: Path, overwrite: bool, max_rows: int) -> int:
    """Stream one TSV shard out of the C4_200M zip into a `(corrupted, corrected)` Parquet, atomically.

    Args:
        zip_path: Path to `data.zip`.
        shard: Zero-based index of the `C4_200M.tsv-NNNNN-of-00010` member to repack.
        out_dir: Directory the `c4_200m-NNNNN.parquet` shard is written under.
        overwrite: Re-repack even if the target Parquet already exists.
        max_rows: Stop after this many pairs (`0` = the whole shard). A small cap stages a quick
            parse-gate sample without materialising the full ~18M-pair shard.

    Returns:
        Process exit code (0 on success / skip, 1 on a missing source / member).
    """
    if not zip_path.is_file():
        print(f"repack_c4_200m: source zip not found: {zip_path}", file=sys.stderr)
        return 1
    member = f"C4_200M.tsv-{shard:05d}-of-00010"
    out_path = out_dir / f"c4_200m-{shard:05d}.parquet"
    out_dir.mkdir(parents=True, exist_ok=True)
    if out_path.exists() and not overwrite:
        print(f"repack_c4_200m: {out_path.name} exists; pass --overwrite to rebuild")
        return 0

    schema = pyarrow.schema([("corrupted", pyarrow.string()), ("corrected", pyarrow.string())])
    tmp_path = out_path.with_suffix(".parquet.tmp")
    corrupted_col: list[str] = []
    corrected_col: list[str] = []
    kept = 0
    writer = pyarrow.parquet.ParquetWriter(str(tmp_path), schema, compression="zstd")
    try:

        def flush() -> None:
            if not corrupted_col:
                return
            writer.write_table(pyarrow.table({"corrupted": corrupted_col, "corrected": corrected_col}, schema=schema))
            corrupted_col.clear()
            corrected_col.clear()

        with zipfile.ZipFile(zip_path) as archive:
            if member not in archive.namelist():
                print(f"repack_c4_200m: member {member} not in zip", file=sys.stderr)
                return 1
            with archive.open(member) as raw:
                text = io.TextIOWrapper(raw, encoding="utf-8", errors="replace", newline="")
                reader = csv.reader((line.replace("\0", " ") for line in text), delimiter="\t", quoting=csv.QUOTE_NONE)
                for row in reader:
                    if len(row) < 2:
                        continue
                    corrupted_col.append(row[0])
                    corrected_col.append(row[1])
                    kept += 1
                    if len(corrupted_col) >= ROW_GROUP_SIZE:
                        flush()
                    if max_rows and kept >= max_rows:
                        break
        flush()
    finally:
        writer.close()
    os.replace(tmp_path, out_path)
    print(f"repack_c4_200m: wrote {kept} (corrupted, corrected) pairs from {member} -> {out_path}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument(
        "--data-root",
        default=DEFAULT_DATA_ROOT,
        help=f"Host data root that `data/c4_200m` symlinks to (default: {DEFAULT_DATA_ROOT}).",
    )
    parser.add_argument("--shard", type=int, default=0, help="Zero-based TSV shard index (0..9) to repack.")
    parser.add_argument("--overwrite", action="store_true", help="Re-repack even if the target parquet exists.")
    parser.add_argument(
        "--max-records",
        type=int,
        default=0,
        help="Stop after this many pairs (0 = whole shard); a small cap stages a quick parse-gate sample.",
    )
    args = parser.parse_args()
    destination = download_c4_200m(args.data_root)
    code = repack(Path(destination) / "data.zip", args.shard, Path(destination), args.overwrite, args.max_records)
    if code != 0:
        return code
    return 0


if __name__ == "__main__":
    sys.exit(main())
